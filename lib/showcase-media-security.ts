/** CSRF guard for Super Admin showcase mutations behind Railway TLS termination.
 * The request URL may be an internal http:// origin; only the operator-configured
 * public HTTPS APP_ORIGIN/CMS_ORIGIN may authorize an authenticated mutation.
 */
import {applicationOrigin} from "./request-origin.ts";
type Environment=Record<string,string|undefined>;
export function showcaseMutationOriginAllowed(
 requestUrl:string,host:string|null,origin:string|null,
 env:Environment=process.env,
):boolean{
 if(!origin||origin==="null")return false;
 // Never use the proxy-provided Host fallback for authenticated mutations
 // in a deployed Railway environment.
 if(env.RAILWAY_ENVIRONMENT_ID&&
   !env.APP_ORIGIN&&!(env.CMS_ENABLED==="true"&&env.CMS_ORIGIN))return false;
 const expected=applicationOrigin(requestUrl,host,env);
 return expected!==null&&origin===expected;
}

/** Only preview images generated by the server under randomUUID() names
 * may be unlinked. In particular do not touch uploaded videos or other
 * private customer media when removing a showcase preview.
 */
export function isShowcasePosterFilename(filename:string):boolean{
 return /^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}\.webp$/i.test(filename);
}
