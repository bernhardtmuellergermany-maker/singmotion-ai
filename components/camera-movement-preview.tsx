"use client";
import {useState} from "react";
import {cameraMovementPreview,type CameraMovement} from "@/lib/studio-camera-movements";
import styles from "./camera-movement-preview.module.css";

/** Native picture avoids image optimizers flattening animated WebP; reduced motion never requests it. */
export function CameraMovementPreview({move}:{move:CameraMovement}){
 const [paused,setPaused]=useState(false);
 const {animation,poster}=cameraMovementPreview(move);
 return <figure className={styles.figure}>
  <picture>
   <source media="(prefers-reduced-motion: reduce)" srcSet={poster}/>
   {/* eslint-disable-next-line @next/next/no-img-element -- animated WebP, local and sized */}
   <img src={paused?poster:animation} alt={move.name+" — illustrative camera movement"} width={640} height={360} loading="lazy" decoding="async"/>
  </picture>
  <figcaption className={styles.caption}>
   <span>Illustrative demonstration. Not generated by OmniHuman 2.0.</span>
   <button type="button" className={styles.pause} aria-label={(paused?"Play ":"Pause ")+move.name+" preview"} onClick={()=>setPaused(value=>!value)}>{paused?"Play":"Pause"}</button>
  </figcaption>
 </figure>;
}
